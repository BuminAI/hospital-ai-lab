// 日本語版 よくあるご質問データ — 型付きローダー
//
// ⚠️ 質問データは JSON に移しました。編集するファイルは
//      src/data/ja/content/faq.json
//    このファイルは JSON を読み込んで型を付けるだけです。質問は書かないこと。
//
// ⚠️ 韓国語版の翻訳ではありません。回答は日本の制度
//    (薬機法・個人情報保護法・次世代医療基盤法など) を前提に書き直しています。
//    出典は実際に接続して、その内容が回答を裏づけるか確認しました。
//
// ⚠️ 配列の順番が画面の順番であり、JSON-LD のアンカー (#q1〜) にもなります。
//    途中に差し込む・削除すると、既存の共有リンクが別の質問を指します。
//
// ⚠️ sources は空でも必ず [] を入れること。また各要素は http(s):// で始まる
//    絶対 URL であること。faq.astro が new URL() で解析するため、
//    スキームが欠けているとビルドが落ちます。
//
// 検証で修正した点:
//   - 保険適用の区分列挙 (A1・A2・B・C1・C2) を削除。現行の区分と異なり、
//     提示した出典でも裏づけられなかったため、区分数に触れない表現に変更。
//   - 出典が回答の一部しか裏づけない項目に、根拠 URL を併記 (sources 配列)。

import faqData from './content/faq.json';

export interface FaqItemJa {
  question: string;
  answer: string;
  /** 出典 URL。複数ある場合はすべて掲載する */
  sources: string[];
}

export const faqItemsJa: FaqItemJa[] = faqData;
